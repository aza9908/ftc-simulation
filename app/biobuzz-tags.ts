export function bioTagTexture(id: number) {
  const rows = PATTERNS[id];
  const data = new Uint8Array(rows.length * rows.length * 4);
  rows
    .slice()
    .reverse()
    .forEach((row, y) =>
      [...row].forEach((v, x) => {
        const i = (y * rows.length + x) * 4;
        data[i] = data[i + 1] = data[i + 2] = v === '1' ? 255 : 0;
        data[i + 3] = 255;
      }),
    );
  const texture = new THREE.DataTexture(data, rows.length, rows.length);
  texture.colorSpace = THREE.SRGBColorSpace;
  texture.magFilter = THREE.NearestFilter;
  texture.minFilter = THREE.NearestFilter;
  texture.needsUpdate = true;
  return texture;
}
